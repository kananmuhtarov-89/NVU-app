def normalize_color(c):
    """
    Rəngi standart qrupa salır.
    Tanınmayan bütün yeni/kirli rənglər avtomatik 'Digər' olur.
    Substring axtarışı yoxdur; məsələn 'niaqara' artıq 'Qara' sayılmır.
    """
    key = _basic_key(c)
    if not key:
        return "Digər"

    if key in COLOR_MAPPING:
        return COLOR_MAPPING[key]

    key2 = _strip_descriptors(key)
    if key2 in COLOR_MAPPING:
        return COLOR_MAPPING[key2]

    return "Digər"
