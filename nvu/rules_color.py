from .cleaning import coerce_str
import re

def _basic_key(x):
    """Rəng adını sabit müqayisə açarına çevirir.
    Məs: 'Qırmızı metallik' -> 'qirmizi metallik'.
    """
    s = (coerce_str(x) or "").strip().lower()
    repl = {
        "ə": "e", "ı": "i", "ö": "o", "ü": "u",
        "ğ": "g", "ş": "s", "ç": "c",
    }
    for a, b in repl.items():
        s = s.replace(a, b)
    s = s.replace("i̇", "i")
    s = re.sub(r"[^a-z0-9]+", " ", s)
    s = re.sub(r"\s+", " ", s).strip()
    return s

def _strip_descriptors(key):
    """Metallik/metal/sədəf/xətt kimi təsviri sözləri silir.
    Bu, 'Qara metallik' və 'Qara' kimi variantları eyni tanımağa kömək edir.
    """
    s = key or ""
    for word in ["metallik", "metallic", "metalik", "metal", "sedef", "perlam", "xett", "mat"]:
        s = re.sub(rf"\b{word}\b", " ", s)
    s = re.sub(r"\s+", " ", s).strip()
    return s

